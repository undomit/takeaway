"""Verify fresh/preceding upgrades and drift detection in a new disposable database."""

import argparse
import tempfile

from runtime_smoke import Stack

DRIFT_CHECK = """
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from app import models
from app.core.db import Base
from sqlalchemy import Column, Integer
config = Config('alembic.ini')
table = Base.metadata.tables['restaurants']
column = Column('unrepresented_ci_probe', Integer)
table.append_column(column)
try:
    command.check(config)
except AutogenerateDiffsDetected:
    print('PASS: unrepresented schema change rejected')
else:
    raise AssertionError('alembic check accepted model drift')
finally:
    table._columns.remove(column)
command.check(config)
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", default="takeaway-app:local")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="takeaway-migrations-") as directory:
        stack = Stack(directory, args.image)
        try:
            stack.compose("up", "-d", "--wait", "db")
            for arguments in (
                ("alembic", "upgrade", "head"),
                ("alembic", "check"),
                ("alembic", "downgrade", "-1"),
                ("alembic", "upgrade", "head"),
                ("alembic", "check"),
                ("python", "-c", DRIFT_CHECK),
            ):
                result = stack.compose("run", "--rm", "--no-deps", "migrate", *arguments)
                print(result.stdout, end="", flush=True)
            print("PASS: fresh head, preceding revision upgrade and drift rejection", flush=True)
        finally:
            stack.cleanup()


if __name__ == "__main__":
    main()
